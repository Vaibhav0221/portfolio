export function Icon({ name, size = 24, className = '', 'aria-hidden': ariaHidden = true, 'aria-label': ariaLabel }: IconProps) {
  const icon = icons[name];

  if (!icon) {
    console.warn(`Icon "${name}" not found`);
    return null;
  }

  const svgIcon = React.isValidElement(icon)
    ? React.cloneElement(icon as React.ReactElement<React.SVGProps<SVGSVGElement>>, {
        width: size,
        height: size,
        'aria-hidden': ariaHidden,
        'aria-label': ariaLabel,
        className: className
      } as React.SVGProps<SVGSVGElement>)
    : (
      <span className={`icon icon--emoji ${className}`} style={{ fontSize: size }} aria-hidden={ariaHidden} aria-label={ariaLabel}>
        {icon}
      </span>
    );

  return svgIcon;
}

export function IconWrapper({ children, className = '', ...props }: { children: React.ReactNode; className?: string } & React.HTMLAttributes<HTMLSpanElement>) {
  return <span className={`icon-wrapper ${className}`} {...props}>{children}</span>;
}